# ------------------------------------------------------------------------------------------------ sinit
def m_sinit(e, a):
    """SUNIT_AnimInit up to its first callee -> (obs pc, args, +0x30, +0x44, +0x4E)."""
    if not e.t("null", a["unit"] != 0):
        raise Fatal()
    t, cls, mode = a["type"], a["cls"], a["mode"]
    p30, p44 = a["p30"], a["p44"]
    seq = (e.t("t0", t == 0) and e.t("m18", mode == 18)) or (e.t("t1", t == 1) and e.t("m14", mode == 14))
    if seq:
        return (OBS_SEQ, (U,), p30, p44, 0)
    if e.t("path", a["path"] != 0):
        return (OBS_RATE, (U, 0x006E10F8, 0x578), 0, 0, 0)
    return (OBS_REC, (U, t, cls, mode), 0, 0, 0)


