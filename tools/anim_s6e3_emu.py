def read_out(path):
    calls, reads, writes, tr = [], [], [], []
    pend = []
    for ln in open(path):
        p = ln.split()
        if not p:
            continue
        if p[0] == "T":
            pend.append(int(p[2], 16))
        elif p[0] == "C":
            c = {"n": int(p[1]), "fn": int(p[2], 16), "dumps": {}, "trace": pend}
            pend = []
            if p[3] == "STOP":
                c["stop"] = int(p[4], 16)
            elif p[3] == "OBS":
                c["obs"] = int(p[4], 16)
            else:
                kv = dict(x.split("=") for x in p[3:])
                c.update(eax=int(kv["eax"], 16), pop=int(kv["pop"]))
            calls.append(c)
        elif p[0] == "A":
            calls[-1]["args"] = struct.unpack("<16I", bytes.fromhex(p[1]))
        elif p[0] == "D":
            calls[-1]["dumps"][int(p[1], 16)] = bytes.fromhex(p[2]) if len(p) > 2 else b""
        elif p[0] in ("R", "W"):
            (reads if p[0] == "R" else writes).append((int(p[1], 16), int(p[2], 16), int(p[3]), int(p[4])))
    return calls, reads, writes


def dwd(c, a):
    return struct.unpack("<I", c["dumps"][a])[0]


def observed(fam, c):
    if c.get("stop") == FATAL[0]:
        return ("fatal",)
    if "stop" in c:
        return ("stop", c["stop"])
    if fam == "sf":
        tr = c["trace"]
        which = None if not tr else ("78" if tr == [TR78] else ("1516" if tr == [TR1516] else tuple(tr)))
        return (c["eax"], which)
    if fam == "adv":
        return (dwd(c, U + 0x44), c["dumps"][U + 0x4E][0])
    if fam == "ainit":
        return (c["eax"], dwd(c, U + 0x44), dwd(c, U + 0x48), struct.unpack("<H", c["dumps"][U + 0x4C])[0],
                c["dumps"][U + 0x4E][0])
    if "obs" not in c:
        return ("returned",)
    nargs = {OBS_SEQ: 1, OBS_RATE: 3, OBS_REC: 4}.get(c["obs"], 0)
    retaddr = c["args"][0]
    return (c["obs"], tuple(c["args"][1:1 + nargs]), dwd(c, U + 0x30), dwd(c, U + 0x44), c["dumps"][U + 0x4E][0],
            retaddr)


RET = {OBS_SEQ: 0x00553420, OBS_RATE: 0x00553460, OBS_REC: 0x0055347F}


def same(fam, want, got):
    if fam == "sinit" and want[0] != "fatal":
        return got[:5] == want and got[5] == RET[want[0]]
    if fam == "adv" and want[0] != "fatal":
        return (u32(want[0]), want[1]) == got
    return tuple(want) == tuple(got)


# ------------------------------------------------------------------------------------------------ bonus, k3
def check_bonus(out):
    """Recount the kept p50b `bonus` run for negative stats against an unsigned and a floor divide."""
    cases, _, exp = AR.fam_bonus(random.Random("p50b-bonus"))
    kept = open(os.path.join(P50B, "bonus.cases")).read()
    regen = "\n".join(cases) + "\n" == kept
    calls, _, _ = AR.read_out(os.path.join(P50B, "bonus.out"))
    neg = bad = 0
    sep = {"unsigned": 0, "floor": 0}
    passed = {"unsigned": 0, "floor": 0}
    for c, (i, v, want) in zip(calls, exp):
        if v >= 0 or "stop" in c:
            continue
        neg += 1
        got = s32(c["eax"])
        if got != want:
            bad += 1
        _, k, _ = AR.BONUS[i]
        alt = {"unsigned": s32(u32(k * v) // u32(k + v)) if u32(k + v) else None,
               "floor": (k * v) // (k + v)}
        for nm, val in alt.items():
            if val != want:
                sep[nm] += 1
                if val == got:
                    passed[nm] += 1
    h = hashlib.sha256(open(os.path.join(P50B, "bonus.out"), "rb").read()).hexdigest()
    out.append("BONUS kept=bonus.out sha256=%s regenerated_cases_identical=%d calls=%d negative=%d bad=%d" %
               (h, int(regen), len(calls), neg, bad))
    for nm in sep:
        out.append("CTRL bonus %s sep=%d passed=%d" % (nm, sep[nm], passed[nm]))
    return bad + sum(passed.values()) + (0 if regen else 1)


def check_k3(out):
    """K3, attack: least IAS s with length <= m is ceil(120 y / (120 - y)), y = X_m - stat68 - terms."""
    n = bad = refine = 0
    sep = passed = 0
    first = {}                                                  # s >= 0: the bonus stays below 120 = k, and
    for s in range(0, 30001):                                   # s = 30 000 already gives 119, so the scan
        first.setdefault(AR.bonus(0, s), s)                     # reaches every value any s >= 0 gives
    for spd in (128, 160, 192, 200, 224, 256, 320, 384, 512):
        for F in range(2, 30):
            for S in (0, 1, 2):
                if F <= S:
                    continue
                lens = {AR.closed_len(F, S, AR.rate_attack(spd, x)) for x in range(15, 176)}
                for m in sorted(lens):
                    xm = AR.least_x(spd, F, S, m)
                    if xm is None:
                        continue
                    for base in (0, 20, 50, 75, 90, 100, 110, 120, 140, 160, 175):
                        for terms in (0, -10, 15):
                            y = xm - base - terms
                            want = AR.least_stat(120, y)
                            if xm == 15 and want != 0:          # the refinement: X_m at the clamp's floor 15 is
                                refine += 1                     # reached with no IAS (J2's clamp), whatever y
                                want = 0
                            got = None                          # brute force through J1 and J2: every bonus value
                            for b, s in first.items():          # and the least s that reaches it
                                if AR.closed_len(F, S, AR.rate_attack(spd, base + terms + b)) <= m:
                                    got = s if got is None else min(got, s)
                            n += 1
                            if got != want:
                                bad += 1
                            if y > 0 and want and xm > 15:
                                fl = (120 * y) // (120 - y)     # the floor control
                                if fl != want:
                                    sep += 1
                                    if fl == got:
                                        passed += 1
    out.append("K3 cases=%d bad=%d refined_at_floor15=%d" % (n, bad, refine))
    out.append("CTRL k3 floor sep=%d passed=%d" % (sep, passed))
    return bad + passed


# ------------------------------------------------------------------------------------------------ check
def cmd_check(d):
    allc = build()
    calls, reads, writes = read_out(os.path.join(d, "s6e3.out"))
    out = []
    bad = 0
    if len(calls) != len(allc):
        out.append("BAD count out=%d cases=%d" % (len(calls), len(allc)))
        bad += 1
    stats = {}
    obs = [observed(f, c) for (f, _), c in zip(allc, calls)]
    for (fam, a), c, got in zip(allc, calls, obs):
        want, _ = predict(fam, a)
        s = stats.setdefault(fam, {"cases": 0, "bad": 0, "stops": 0, "fatal": 0})
        s["cases"] += 1
        if got[0] == "stop":
            s["stops"] += 1
        if want[0] == "fatal":
            s["fatal"] += 1
        if not same(fam, want, got):
            s["bad"] += 1
            if s["bad"] <= 5:
                out.append("BAD %s case=%d want=%s got=%s" % (fam, c["n"], want, got))
    for fam in FAMILIES:
        s = stats.get(fam, {})
        out.append("FAMILY %s %s" % (fam, " ".join("%s=%d" % kv for kv in s.items())))
        bad += s.get("bad", 0) + s.get("stops", 0)
    # tallies the rows rest on
    t = {}
    for (fam, a), got in zip(allc, obs):
        if fam == "sf" and a["type"] == 0:
            k = "sf-read%s-cls%d" % (got[1], a["cls"]) if got[1] else None
            if k:
                t[k] = t.get(k, 0) + 1
        if fam == "adv":
            S = m_sf(E(), a)[0]
            w = s32(a["pos"] + s16(a["r"])) >= a["L"]
            if w and S:
                t["adv-wrap-S%d" % S] = t.get("adv-wrap-S%d" % S, 0) + 1
            if s16(a["r"]) < 0x100 and a["ev"] is not None and not w:
                p = a["pos"] >> 8
                if a["ev"][p] in (1, 2, 3, 4) and all(a["ev"][x] not in (1, 2, 3, 4)
                                                      for x in range(p + 1, (s32(a["pos"] + s16(a["r"])) >> 8) + 1)):
                    t["adv-rescan-only"] = t.get("adv-rescan-only", 0) + 1
        if fam == "sinit" and len(got) > 1:
            t["sinit-obs-%08x" % got[0]] = t.get("sinit-obs-%08x" % got[0], 0) + 1
        if fam == "ainit":
            t["ainit-t%d-ret%d" % (a["type"], got[0])] = t.get("ainit-t%d-ret%d" % (a["type"], got[0]), 0) + 1
            if a["type"] == 3 and got[0] == 1 and s16(a["rate"]) < 0 and (s16(a["rate"]) << 8) % 1024:
                t["ainit-negative-inexact"] = t.get("ainit-negative-inexact", 0) + 1
    out += ["TALLY %s %d" % kv for kv in sorted(t.items())]
    # controls
    names = {}
    for fam, a in allc:
        _, nm = predict(fam, a)
        names.setdefault(fam, set()).update(nm)
    unsep = []
    for fam in FAMILIES:
        for nm in sorted(names[fam]):
            sep = passed = 0
            for (f, a), got in zip(allc, obs):
                if f != fam:
                    continue
                base, _ = predict(f, a)
                alt, _ = predict(f, a, nm)
                if alt != base:
                    sep += 1
                    if alt[0] != "fatal" and same(f, alt, got):
                        passed += 1
            out.append("CTRL %s %s sep=%d passed=%d" % (fam, nm, sep, passed))
            bad += passed
            if sep == 0:
                unsep.append("%s:%s" % (fam, nm))
    out.append("UNSEPARATED %s" % (" ".join(unsep) or "none"))
    # traced accesses
    un = 0
    for pc, addr, size, cnt in reads:
        if not any(lo <= addr and addr + size <= lo + n for lo, n, _ in CONST_READS):
            un += 1
            out.append("READ pc=%08x addr=%08x size=%d n=%d" % (pc, addr, size, cnt))
    for pc, addr, size, cnt in writes:
        un += 1
        out.append("WRITE pc=%08x addr=%08x size=%d n=%d" % (pc, addr, size, cnt))
    out.append("ACCESS reads=%d writes=%d unaccounted=%d" % (len(reads), len(writes), un))
    bad += un
    bad += check_bonus(out)
    bad += check_k3(out)
    out.append("SCAN check bad=%d" % bad)
    txt = "\n".join(out) + "\n"
    open(os.path.join(d, "check.txt"), "w").write(txt)
    sys.stdout.write(txt)
    return 0 if bad == 0 else 1


def cmd_manifest(d, write):
    names = ["s6e3.cases", "s6e3.mem", "s6e3-dt.bin", "s6e3.out", "s6e3.err", "check.txt"]
    lines = ["%s  %s" % (hashlib.sha256(open(os.path.join(d, n), "rb").read()).hexdigest(), n) for n in names]
    if write:
        open(os.path.join(d, "manifest.sha256"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["cases", "check", "manifest"])
    ap.add_argument("--dir", default=DEFAULT_DIR)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    if a.cmd == "cases":
        return cmd_cases(a.dir) or 0
    if a.cmd == "check":
        return cmd_check(a.dir)
    return cmd_manifest(a.dir, a.write) or 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
