# ------------------------------------------------------------------------------------------------ ainit
def m_ainit(e, a):
    """UNIT_AnimInit, type 3 or 4 -> (return, +0x44, +0x48, +0x4C u16, +0x4E)."""
    p44, p48, p4c = 0, a["p48"], a["p4c"]
    if e.t("t3", a["type"] == 3):
        cls = s32(a["cls"])
        if not (e.c("cneg", cls, ">=", 0) and e.c("cnt", cls, "<", MI_N)):
            return (0, p44, p48, p4c, 0)
        ar = s16(a["rate"])
        v = ar << 8
        q = (abs(v) >> 10) * (1 if v >= 0 else -1) if e.t("trunc", True) else v >> 10
        return (1, p44, (a["len"] & 0xFF) << 8, q & 0xFFFF, 0)
    if e.t("m3", a["mode"] == 3):
        return (1, 0x1000, 0x1100, 0, 0)
    if e.t("m5", a["mode"] == 5):
        return (1, p44, 0x1100, 0x100, 0)
    return (1, p44, p48, p4c, 0)


