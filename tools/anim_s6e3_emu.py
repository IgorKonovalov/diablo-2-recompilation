def cell(wc, cls):
    return Img.dw(ASF + 4 * (wc * 7 + cls))


# ------------------------------------------------------------------------------------------------ sf
def m_sf(e, a):
    """UNIT_AnimStartFrame, no inventory -> (return, which table read ran: None, '78' or '1516')."""
    t, cls, mode = a["type"], a["cls"], a["mode"]
    if not e.t("t0", t == 0):
        return 0, None
    if e.t("m78", mode in (7, 8)):
        return cell(0, cls), "78"
    if e.t("m1516", mode in (15, 16)):
        if e.t("dual", cls in (4, 6)):                          # UNIT_CanDualWield, type 0: class 4 or 6
            return cell(0, cls), "1516"
    return 0, None


def gen_sf(rnd):
    out = []
    for t in (0, 1, 2, 3, 4):
        for cls in range(7):
            for mode in range(21):
                out.append(dict(type=t, cls=cls, mode=mode))
    for _ in range(300):
        out.append(dict(type=rnd.choice([0, 0, 1]), cls=rnd.choice([0x1A1, 0x1A2, rnd.randrange(7)]),
                        mode=rnd.choice([7, 8, 15, 16, rnd.randrange(21)])))
    return [a for a in out if not (a["type"] == 0 and a["cls"] > 6)]


def unit_lines(a, extra=()):
    ln = ["w %08x %s" % (U, le32(a["type"]).hex()), "w %08x %s" % (U + 4, le32(a["cls"]).hex()),
          "w %08x %s" % (U + 0x10, le32(a["mode"]).hex())]
    return ln + list(extra)


def case_sf(a):
    return unit_lines(a) + ["call %08x 00000000 00000000 %08x" % (FNS["sf"], U)]


# ------------------------------------------------------------------------------------------------ adv
def m_adv(e, a):
    """UNIT_AnimAdvance, +0x30 = 0, display type 0 -> (+0x44, +0x4E)."""
    pos, L, r, ev = a["pos"], a["L"], a["r"], a["ev"]
    S = m_sf(e, a)[0]
    f = pos >> 8
    if e.c("r100", s16(r), ">=", 0x100):
        f += 1
    pos = s32(pos + s16(r))
    out = 0

    def take(x):
        nonlocal out
        if ev is not None and e.c("b90", x, "<", 0x90) and ev[x] in (1, 2, 3, 4):
            out = ev[x]
    guard = 0
    while e.c("wrap", pos, ">=", L):
        while e.c("lf", f, "<", L >> 8):
            take(f)
            f += 1
            if f > 0x400:
                raise Fatal()
        pos -= L
        f = 0
        if e.t("sadd", True):
            pos += S << 8
        guard += 1
        if guard > 1000:
            raise Fatal()                                       # a reversed loop test: no case matches
    while e.c("tail", f, "<=", pos >> 8):
        take(f)
        f += 1
        if f > 0x400:
            raise Fatal()
    return u32(pos), out


def gen_adv(rnd):
    out = []
    for k in range(4000):
        cls = rnd.choice([0, 1, 0, 1, rnd.randrange(7)])
        mode = rnd.choice([7, 8, 7, 8, 15, 16, rnd.randrange(21)])
        F = rnd.choice([1, 2, 3, 4, 6, 8, 12, 16, 18, 20, 0x8F, 0x90, 0x91, 0xA0])
        S = m_sf(E(), dict(type=0, cls=cls, mode=mode))[0]
        if F <= S:                                              # a wrap with S >= F never ends: the loop takes L
            F = S + rnd.choice([1, 2, 6])                       # and adds S << 8 >= L back (development run, case 1369)
        L = F << 8
        ev = [0] * 0x100
        sep43 = k % 4 == 0
        if sep43:                                               # an event on the frame stood on only
            pos = rnd.randrange(0, L)
            ev[pos >> 8] = rnd.choice([1, 2, 3, 4])
            r = rnd.choice([1, 0x40, 0x80, 0xFF, 0x100, 0x101, 0x180, rnd.randrange(0, 0x100)])
        else:
            for _ in range(rnd.choice([0, 1, 3, 10, 40])):
                ev[rnd.randrange(0x100)] = rnd.choice([1, 2, 3, 4, 5, 0xFF])
            pos = rnd.randrange(0, L)
            r = rnd.choice([0, 1, 0x40, 0x80, 0xFF, 0x100, 0x101, 0x180, 0x200, 0x300, rnd.randrange(0, 0x800),
                            L - pos, L - pos + 1, L - pos - 1, rnd.randrange(0, 0x8000)])
        rec = rnd.random() > 0.03
        out.append(dict(type=0, cls=cls, mode=mode, pos=pos, L=L, r=r & 0xFFFF, ev=ev[:0x90] + [0] * 0x70 if rec
                        else None))
    for i in range(len(out)):                                   # the model reads events past 0x90 only through b90
        if out[i]["ev"] is not None:
            out[i]["ev"] = out[i]["ev"][:0x90] + [rnd.choice([0, 1, 2, 3, 4]) for _ in range(0x30)]
    return out


